@ft.cache
def get_name(spkgs: str) -> Optional[str]:
    for name in ALL_PACKAGES:
        if name in spkgs:
            return name
    return None

def get_name_or_raw(spkgs: str) -> str:
    name = get_name(spkgs)
    if name:
        return name
    else:
        return spkgs

